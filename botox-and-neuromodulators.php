<script>
document.addEventListener('DOMContentLoaded', function() {
    // Initialize all comparison containers
    const comparisons = document.querySelectorAll('.comparison-container');
    
    comparisons.forEach((comparison, index) => {
        initializeSlider(comparison, index);
    });

    function initializeSlider(comparison, index) {
        const sliderHandle = comparison.querySelector('.slider-handle');
        const afterImage = comparison.querySelector('.after-image');
        const beforeBadge = comparison.querySelector('.badge-before');
        const afterBadge = comparison.querySelector('.badge-after');
        
        if (!sliderHandle || !afterImage || !beforeBadge || !afterBadge) {
            console.error(`Slider elements not found for slider ${index}`);
            return;
        }
        
        let isActive = false;
        let currentX = 50;

        function updateSlider(percentage) {
            percentage = Math.max(0, Math.min(100, percentage));
            currentX = percentage;
            
            sliderHandle.style.left = percentage + '%';
            afterImage.style.clipPath = `polygon(${percentage}% 0%, 100% 0%, 100% 100%, ${percentage}% 100%)`;
            
            // Update badge visibility based on slider position
            updateBadgeVisibility(percentage);
        }

        function updateBadgeVisibility(percentage) {
            // If slider is more towards left (showing more before image) - Show AFTER badge
            if (percentage < 50) {
                beforeBadge.classList.add('hide');
                beforeBadge.classList.remove('show');
                afterBadge.classList.add('show');
                afterBadge.classList.remove('hide');
            } 
            // If slider is more towards right (showing more after image) - Show BEFORE badge
            else if (percentage > 50) {
                beforeBadge.classList.add('show');
                beforeBadge.classList.remove('hide');
                afterBadge.classList.add('hide');
                afterBadge.classList.remove('show');
            }
            // If slider is in the middle, show both badges
            else {
                beforeBadge.classList.remove('hide', 'show');
                afterBadge.classList.remove('hide', 'show');
            }
        }

        function getPercentageFromEvent(e) {
            const rect = comparison.getBoundingClientRect();
            const clientX = e.clientX || (e.touches && e.touches[0].clientX);
            const x = clientX - rect.left;
            return (x / rect.width) * 100;
        }

        // Mouse events
        comparison.addEventListener('mousedown', (e) => {
            isActive = true;
            const percentage = getPercentageFromEvent(e);
            updateSlider(percentage);
            e.preventDefault();
        });

        document.addEventListener('mousemove', (e) => {
            if (!isActive) return;
            const percentage = getPercentageFromEvent(e);
            updateSlider(percentage);
        });

        document.addEventListener('mouseup', () => {
            isActive = false;
        });

        // Touch events for mobile
        comparison.addEventListener('touchstart', (e) => {
            isActive = true;
            const percentage = getPercentageFromEvent(e);
            updateSlider(percentage);
            e.preventDefault();
        });

        document.addEventListener('touchmove', (e) => {
            if (!isActive) return;
            const percentage = getPercentageFromEvent(e);
            updateSlider(percentage);
            e.preventDefault();
        });

        document.addEventListener('touchend', () => {
            isActive = false;
        });

        // Click event
        comparison.addEventListener('click', (e) => {
            if (!isActive) {
                const percentage = getPercentageFromEvent(e);
                updateSlider(percentage);
            }
        });

        // Initialize slider position
        updateSlider(50);
    }
});
</script>

    

