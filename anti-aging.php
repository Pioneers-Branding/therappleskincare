   <script>
      // Tab functionality
      document.addEventListener('DOMContentLoaded', function () {
         const tabButtons = document.querySelectorAll('.tab-button');
         const tabPanels = document.querySelectorAll('.tab-content-panel');

         tabButtons.forEach(button => {
            button.addEventListener('click', () => {
               const targetTab = button.getAttribute('data-tab');

               // Remove active classes
               tabButtons.forEach(btn => btn.classList.remove('tab-active'));
               tabPanels.forEach(panel => panel.classList.remove('panel-active'));

               // Add active classes
               button.classList.add('tab-active');
               document.getElementById(targetTab + '-content').classList.add('panel-active');

               // Reinitialize slider for the active tab
               initializeSlider(targetTab + '-comparison');
            });
         });

         // Initialize sliders
         initializeSlider('filler-comparison');
         initializeSlider('laser-comparison');

         function initializeSlider(containerId) {
            const container = document.getElementById(containerId);
            if (!container) return;

            const slider = container.querySelector('.comparison-slider');
            const afterImage = container.querySelector('.after-image');
            let isDragging = false;

            function updateSlider(x) {
               const containerRect = container.getBoundingClientRect();
               const percentage = Math.max(0, Math.min(100, ((x - containerRect.left) / containerRect.width) * 100));

               slider.style.left = percentage + '%';
               afterImage.style.clipPath = `inset(0 ${100 - percentage}% 0 0)`;
            }

            // Mouse events
            slider.addEventListener('mousedown', (e) => {
               isDragging = true;
               e.preventDefault();
            });

            document.addEventListener('mousemove', (e) => {
               if (!isDragging) return;
               updateSlider(e.clientX);
            });

            document.addEventListener('mouseup', () => {
               isDragging = false;
            });

            // Touch events for mobile
            slider.addEventListener('touchstart', (e) => {
               isDragging = true;
               e.preventDefault();
            });

            document.addEventListener('touchmove', (e) => {
               if (!isDragging) return;
               e.preventDefault();
               const touch = e.touches[0];
               updateSlider(touch.clientX);
            });

            document.addEventListener('touchend', () => {
               isDragging = false;
            });

            // Click to move slider
            container.addEventListener('click', (e) => {
               if (e.target === slider || slider.contains(e.target)) return;
               updateSlider(e.clientX);
            });
         }
      });
   </script>
   
       <script>
        // Global variables
        var prpCurrentSlide = 0;
        var prpSlidesPerView = 2;
        var prpTotalSlides = 6;
        var prpMaxSlide = 2;

        // Wait for DOM to be fully loaded
        document.addEventListener('DOMContentLoaded', function() {
            // Initialize variables
            prpTotalSlides = document.querySelectorAll('.prp-slide-item').length;
            prpUpdateSlidesPerView();
            
            // Initialize slider
            prpGenerateDots();
            prpUpdateSlider();

            // Handle window resize
            window.addEventListener('resize', function() {
                prpUpdateSlidesPerView();
            });

            // Touch/Swipe support for mobile
            var prpStartX = 0;
            var prpEndX = 0;

            var sliderWrapper = document.querySelector('.prp-slider-wrapper-container');
            if (sliderWrapper) {
                sliderWrapper.addEventListener('touchstart', function(e) {
                    prpStartX = e.touches[0].clientX;
                });

                sliderWrapper.addEventListener('touchend', function(e) {
                    prpEndX = e.changedTouches[0].clientX;
                    prpHandleSwipe();
                });
            }

            function prpHandleSwipe() {
                var threshold = 50;
                var diff = prpStartX - prpEndX;

                if (Math.abs(diff) > threshold) {
                    if (diff > 0) {
                        prpNextSlide();
                    } else {
                        prpPreviousSlide();
                    }
                }
            }
        });

        function prpUpdateSlidesPerView() {
            prpSlidesPerView = window.innerWidth > 768 ? 2 : 1;
            prpMaxSlide = Math.ceil(prpTotalSlides / prpSlidesPerView) - 1;
            if (prpCurrentSlide > prpMaxSlide) {
                prpCurrentSlide = prpMaxSlide;
            }
            prpUpdateSlider();
            prpGenerateDots();
        }

        function prpUpdateSlider() {
            var sliderTrack = document.getElementById('prpSliderTrack');
            if (sliderTrack) {
                var slideWidth = 100 / prpSlidesPerView;
                var translateX = prpCurrentSlide * slideWidth;
                sliderTrack.style.transform = 'translateX(-' + translateX + '%)';
                prpUpdateDots();
            }
        }

        function prpNextSlide() {
            if (prpCurrentSlide >= prpMaxSlide) {
                prpCurrentSlide = 0;
            } else {
                prpCurrentSlide = prpCurrentSlide + 1;
            }
            prpUpdateSlider();
        }

        function prpPreviousSlide() {
            if (prpCurrentSlide <= 0) {
                prpCurrentSlide = prpMaxSlide;
            } else {
                prpCurrentSlide = prpCurrentSlide - 1;
            }
            prpUpdateSlider();
        }

        function prpGoToSlide(slideIndex) {
            prpCurrentSlide = slideIndex;
            prpUpdateSlider();
        }

        function prpGenerateDots() {
            var dotsContainer = document.getElementById('prpDotsContainer');
            if (dotsContainer) {
                var totalDots = Math.ceil(prpTotalSlides / prpSlidesPerView);
                dotsContainer.innerHTML = '';

                for (var i = 0; i < totalDots; i++) {
                    var dot = document.createElement('span');
                    dot.classList.add('prp-dot-indicator');
                    if (i === prpCurrentSlide) {
                        dot.classList.add('prp-dot-active');
                    }
                    
                    // Use closure to capture the current value of i
                    (function(index) {
                        dot.addEventListener('click', function() {
                            prpGoToSlide(index);
                        });
                    })(i);
                    
                    dotsContainer.appendChild(dot);
                }
            }
        }

        function prpUpdateDots() {
            var dots = document.querySelectorAll('.prp-dot-indicator');
            for (var i = 0; i < dots.length; i++) {
                if (i === prpCurrentSlide) {
                    dots[i].classList.add('prp-dot-active');
                } else {
                    dots[i].classList.remove('prp-dot-active');
                }
            }
        }
    </script>
   
